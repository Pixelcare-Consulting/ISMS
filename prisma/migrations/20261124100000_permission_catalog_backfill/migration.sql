-- Monthly SIR: Team Leaders (tl) and Product Specialists (ps) own the P-COUNT upload
-- allowance, and roles with inventory.manage approve Monthly SIR requests.
INSERT INTO "role_permissions" ("id", "role_id", "permission_id", "created_at")
SELECT gen_random_uuid()::text, r."id", monthly_sir_view."id", NOW()
FROM "roles" AS r
INNER JOIN "tenants" AS t ON t."id" = r."tenant_id"
CROSS JOIN "permissions" AS monthly_sir_view
WHERE monthly_sir_view."slug" = 'inventory.monthly_sir.view'
  AND r."deleted_at" IS NULL
  AND t."is_platform" = false
  AND (
    r."slug" IN ('tl', 'ps')
    OR EXISTS (
      SELECT 1
      FROM "role_permissions" AS existing
      INNER JOIN "permissions" AS manage
        ON manage."id" = existing."permission_id"
        AND manage."slug" = 'inventory.manage'
      WHERE existing."role_id" = r."id"
    )
  )
ON CONFLICT ("role_id", "permission_id") DO NOTHING;
